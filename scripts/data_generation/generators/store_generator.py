def generate_dim_store_records(store_count: int = 5) -> List[Dict[str, Any]]:
    """
    Generates store dimension records based on store_count.
    DEV: 5 stores (one in each state: KA, MH, TN, TS, GJ).
    INTEGRATION: 30 stores.
    """
    selected = ALL_30_STORES[:store_count]
    records = []

    # SCD2 Baseline: 2020-01-01 00:00:00 UTC to 9999-12-31 23:59:59 UTC
    eff_from = datetime(2020, 1, 1, 0, 0, 0, tzinfo=timezone.utc)
    eff_to = datetime(9999, 12, 31, 23, 59, 59, tzinfo=timezone.utc)

    for s in selected:
        monthly_rent = s["monthly_lease_rent_inr"]
        daily_rent = (monthly_rent / Decimal("30.0")).quantize(Decimal("0.01"))

        records.append({
            "store_id": s["store_id"],
            "store_name": s["store_name"],
            "store_tier": s["store_tier"],
            "city": s["city"],
            "state": s["state"],
            "region": s["region"],
            "carpet_area_sqft": s["carpet_area_sqft"],
            "backroom_storage_sqft": s["backroom_storage_sqft"],
            "monthly_lease_rent_inr": monthly_rent,
            "daily_allocated_rent_inr": daily_rent,
            "store_manager_employee_id": s["store_manager_employee_id"],
            "operating_status": "OPEN",
            "effective_from_timestamp": eff_from,
            "effective_to_timestamp": eff_to,
            "is_current_flag": True,
        })

    return records
